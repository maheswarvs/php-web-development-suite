<?php
declare(strict_types=1);
require __DIR__ . '/../includes/layout.php';

date_default_timezone_set('Asia/Kolkata');   // change to your server's zone if needed
$now = new DateTimeImmutable();

page_head('Date and time', '../', '2');
?>
<div class="stage">
  <h1>Time, from two sources.</h1>
  <p class="lead">PHP reads the server's clock once, when the page loads. JavaScript then keeps a live clock running.</p>

  <div class="grid2">
    <section class="panel" aria-labelledby="php-h">
      <span class="src php">Generated by PHP · fixed at page load</span>
      <h2 id="php-h">Server snapshot</h2>
      <div class="row"><span>Date</span><span><?= e($now->format('d F Y')) ?></span></div>
      <div class="row"><span>Time</span><span><?= e($now->format('h:i:s A')) ?></span></div>
      <div class="row"><span>Day</span><span><?= e($now->format('l')) ?></span></div>
      <div class="row"><span>Time zone</span><span><?= e($now->format('e (P)')) ?></span></div>
    </section>

    <section class="panel" aria-labelledby="js-h">
      <span class="src js">Updated by JavaScript · every second</span>
      <h2 id="js-h">Live clock</h2>
      <div class="clock" id="clock" role="timer" aria-live="off">--:--<span class="sec">:--</span></div>
      <div class="row" style="margin-top:1rem"><span>Date</span><span id="d">–</span></div>
      <div class="row"><span>Day</span><span id="w">–</span></div>
    </section>
  </div>
</div>
<?php page_foot('<script>
// Anchored to the server time so it matches the PHP panel, then advanced by the browser clock.
const offset = ' . ($now->getTimestamp() * 1000) . ' - Date.now();
const tz = ' . json_encode($now->format('e')) . ';
const fmt = o => new Intl.DateTimeFormat("en-GB", Object.assign({timeZone: tz}, o));
const hms = fmt({hour:"2-digit",minute:"2-digit",second:"2-digit",hour12:true});
const dateF = fmt({day:"2-digit",month:"long",year:"numeric"}), dayF = fmt({weekday:"long"});
function tick(){
  const n = new Date(Date.now() + offset);
  const m = hms.format(n).match(/(\d+):(\d+):(\d+)\s*(\w+)/i);
  document.getElementById("clock").innerHTML = m[1]+":"+m[2]+\'<span class="sec">:\'+m[3]+"</span> <small style=\'font-size:.3em\'>"+m[4].toUpperCase()+"</small>";
  document.getElementById("d").textContent = dateF.format(n);
  document.getElementById("w").textContent = dayF.format(n);
}
tick(); setInterval(tick, 1000);
</script>');
